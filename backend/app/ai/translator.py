def translate_text_en_hi(text: str, source_lang: str = "en", target_lang: str = "hi") -> str:
    """Translates text while preserving technical terminology and headings."""
    src = source_lang.lower()
    tgt = target_lang.lower()

    if src == tgt:
        return text

    translated = text

    # English to Hindi
    if "en" in src and "hi" in tgt:
        # 1. Translate common structural phrases
        for phrase, hi_phrase in COMMON_PHRASE_EN_TO_HI.items():
            translated = re.sub(re.escape(phrase), hi_phrase, translated, flags=re.IGNORECASE)

        # 2. Preserve & map technical terms
        for term, hi_term in TECHNICAL_GLOSSARY_EN_TO_HI.items():
            translated = re.sub(r'\b' + re.escape(term) + r'\b', hi_term, translated, flags=re.IGNORECASE)

        # 3. Translate standard sentence markers
        translated = re.sub(r'\bPage\b', 'पृष्ठ', translated)
        translated = re.sub(r'\bChapter\b', 'अध्याय', translated)
        translated = re.sub(r'\bSection\b', 'खंड', translated)
        translated = re.sub(r'\bStatus: Verified\b', 'स्थिति: सत्यापित (Verified)', translated)
        translated = re.sub(r'\bYes\b', 'हाँ', translated)
        translated = re.sub(r'\bNo\b', 'नहीं', translated)
        translated = re.sub(r'\bDate\b', 'दिनांक', translated)

    # Hindi to English
    elif "hi" in src and "en" in tgt:
        for term, hi_term in TECHNICAL_GLOSSARY_EN_TO_HI.items():
            clean_hi = hi_term.split()[0]
            translated = translated.replace(hi_term, term)
            translated = translated.replace(clean_hi, term)
        translated = translated.replace('पृष्ठ', 'Page')
        translated = translated.replace('अध्याय', 'Chapter')
        translated = translated.replace('निष्कर्ष', 'Conclusion')
        translated = translated.replace('परिचय', 'Introduction')
        translated = translated.replace('सारांश', 'Summary')

    return translated

def generate_translated_docx(translated_text: str, title: str) -> bytes:
    """Generate clean DOCX document of translated content."""
    doc = docx.Document()
    
    # Title
    p_title = doc.add_paragraph()
    r_title = p_title.add_run(f"Translated Document: {title}")
    r_title.bold = True
    r_title.font.size = Pt(18)
    r_title.font.color.rgb = RGBColor(128, 0, 32)
    p_title.paragraph_format.space_after = Pt(12)

    # Subtitle
    p_sub = doc.add_paragraph()
    r_sub = p_sub.add_run("Generated by AI PDF Translator Studio • Technical Terminology Preserved")
    r_sub.italic = True
    r_sub.font.size = Pt(10)
    r_sub.font.color.rgb = RGBColor(100, 116, 139)
    p_sub.paragraph_format.space_after = Pt(18)

    # Paragraphs
    for line in translated_text.splitlines():
        clean_l = line.strip()
        if clean_l:
            p = doc.add_paragraph()
            r = p.add_run(clean_l)
            r.font.size = Pt(11)
            r.font.color.rgb = RGBColor(30, 41, 59)
            p.paragraph_format.space_after = Pt(6)

    out = io.BytesIO()
    doc.save(out)
    return out.getvalue()

